#!/usr/bin/env node
/**
 * build-vocabulary.mjs — regenerate specs/vocabulary.md from the code.
 *
 * The vocabulary is the project's shared asset: one phrase must mean one thing everywhere.
 * Generating it from the step declarations rather than maintaining it by hand is the only way
 * it stays true — a catalogue that drifts is worse than none, because people trust it.
 *
 * The prose->Gherkin skill reads this file to phrase new criteria in vocabulary that already
 * has an implementation, and asks the test-generation skill for additions.
 *
 * What it can flag: the same phrase implemented in two places (which one wins?), and
 * near-identical phrasings (typos, singular/plural, one word swapped). What it cannot flag:
 * true synonyms like "an administrator {string} is logged in" vs "{string} as admin" — no
 * string metric sees those as related. Catching those is why the catalogue is meant to be
 * *read* before new criteria are written, not just diffed.
 *
 * Usage: node build-vocabulary.mjs [--check]
 *   --check  do not write; exit 1 if the file on disk is out of date (useful in CI)
 */
import { readFileSync, writeFileSync, mkdirSync, readdirSync, existsSync, statSync } from 'node:fs';
import { join, relative, sep } from 'node:path';

const ROOT = process.cwd();
const OUT = join(ROOT, 'specs', 'vocabulary.md');
const SCAN = ['src', 'e2e'];
const KEYWORDS = ['Given', 'When', 'Then', 'And', 'But', 'Step'];
const ORDER = ['Given', 'When', 'Then', 'And', 'But', 'Step'];

/** `Given('phrase', fn)` — a declaration. Destructuring (`({ Given })`) has no quote, so it is skipped. */
const DECL = new RegExp(`\\b(${KEYWORDS.join('|')})\\s*\\(\\s*(['"\`])((?:\\\\.|(?!\\2)[^\\\\])*)\\2`, 'g');

function walk(dir, hits = []) {
  if (!existsSync(dir)) return hits;
  for (const entry of readdirSync(dir)) {
    if (entry === 'node_modules' || entry.startsWith('.')) continue;
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) walk(full, hits);
    else if (/\.(spec|steps)\.ts$/.test(entry)) hits.push(full);
  }
  return hits;
}

function normalize(phrase) {
  return phrase
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/\{[a-z]*\}/g, '·')
    .replace(/<[^>]+>/g, '·')
    .replace(/"[^"]*"|'[^']*'/g, '·')
    .replace(/[^a-z0-9· ]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

/** Dice coefficient on word bigrams: robust to a swapped word, blind to true synonyms. */
function similarity(a, b) {
  const grams = (s) => {
    const w = s.split(' ');
    return new Set(w.length < 2 ? w : w.slice(0, -1).map((x, i) => `${x} ${w[i + 1]}`));
  };
  const [ga, gb] = [grams(a), grams(b)];
  if (!ga.size || !gb.size) return 0;
  let shared = 0;
  for (const g of ga) if (gb.has(g)) shared++;
  return (2 * shared) / (ga.size + gb.size);
}

const steps = [];
for (const base of SCAN) {
  for (const file of walk(join(ROOT, base))) {
    const rel = relative(ROOT, file).split(sep).join('/');
    const lines = readFileSync(file, 'utf8').split('\n');
    lines.forEach((line, i) => {
      for (const m of line.matchAll(DECL)) {
        steps.push({
          keyword: m[1],
          phrase: m[3],
          normalized: normalize(m[3]),
          file: rel,
          line: i + 1,
          scope: /\.steps\.ts$/.test(rel) ? 'shared' : 'local',
          level: rel.startsWith('e2e/') ? 'e2e' : 'component',
        });
      }
    });
  }
}

// Same phrase declared in several shared modules: ambiguous, one silently wins.
const byNorm = new Map();
for (const s of steps) {
  const key = `${s.keyword}|${s.normalized}`;
  if (!byNorm.has(key)) byNorm.set(key, []);
  byNorm.get(key).push(s);
}
const conflicts = [...byNorm.values()].filter(
  (group) => group.filter((s) => s.scope === 'shared' && s.level === group[0].level).length > 1,
);

// Near-identical phrasings within the same keyword: likely one phrase written two ways.
const nearDuplicates = [];
const unique = [...byNorm.entries()].map(([key, group]) => ({ key, ...group[0] }));
for (let i = 0; i < unique.length; i++) {
  for (let j = i + 1; j < unique.length; j++) {
    if (unique[i].keyword !== unique[j].keyword) continue;
    if (unique[i].normalized === unique[j].normalized) continue;
    const score = similarity(unique[i].normalized, unique[j].normalized);
    if (score >= 0.6) nearDuplicates.push({ a: unique[i], b: unique[j], score });
  }
}
nearDuplicates.sort((x, y) => y.score - x.score);

const shared = steps.filter((s) => s.scope === 'shared').length;
const out = [];
out.push('# Step vocabulary');
out.push('');
out.push('Generated by `.claude/skills/test-generation/scripts/build-vocabulary.mjs` — do not edit by hand.');
out.push('');
out.push(`${byNorm.size} distinct phrases across ${steps.length} declarations (${shared} shared, ${steps.length - shared} local).`);
out.push('');
out.push('Reuse a phrase that is already here rather than inventing a variant: one phrase, one meaning.');
out.push('A phrase you need that is absent is a request for the test-generation skill, not a licence to');
out.push('rephrase an existing one.');

for (const kw of ORDER) {
  const group = unique.filter((s) => s.keyword === kw);
  if (!group.length) continue;
  group.sort((a, b) => a.normalized.localeCompare(b.normalized));
  out.push('', `## ${kw}`, '', '| Phrase | Scope | Level | Declared in |', '|---|---|---|---|');
  for (const s of group) {
    const all = byNorm.get(s.key);
    const where = all.map((d) => `\`${d.file}:${d.line}\``).join('<br>');
    out.push(`| \`${s.phrase}\` | ${s.scope} | ${s.level} | ${where} |`);
  }
}

if (conflicts.length) {
  out.push('', '## Conflicting declarations', '');
  out.push('The same phrase is implemented in more than one shared module at the same level. One wins');
  out.push('silently, which makes behaviour depend on import order — collapse them into one.');
  out.push('');
  for (const group of conflicts) {
    out.push(`- \`${group[0].keyword} ${group[0].phrase}\``);
    for (const d of group) out.push(`  - \`${d.file}:${d.line}\``);
  }
}

if (nearDuplicates.length) {
  out.push('', '## Possible duplicates', '');
  out.push('Near-identical phrasings for the same keyword. If two of these mean the same thing, keep one');
  out.push('and report the change — the `.feature` files that use the other must be updated by their owner.');
  out.push('');
  for (const { a, b, score } of nearDuplicates.slice(0, 25)) {
    out.push(`- ${(score * 100).toFixed(0)}% — \`${a.phrase}\` (${a.file}:${a.line})`);
    out.push(`  vs \`${b.phrase}\` (${b.file}:${b.line})`);
  }
}

out.push('');
const content = out.join('\n');

if (process.argv.includes('--check')) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (current === content) {
    console.log(`✓ ${relative(ROOT, OUT)} is up to date (${byNorm.size} phrases).`);
    process.exit(0);
  }
  console.error(`✗ ${relative(ROOT, OUT)} is out of date — run build-vocabulary.mjs.`);
  process.exit(1);
}

mkdirSync(join(ROOT, 'specs'), { recursive: true });
writeFileSync(OUT, content);
console.log(`✓ ${relative(ROOT, OUT)}: ${byNorm.size} phrases, ${shared} shared, ${steps.length - shared} local.`);
if (conflicts.length) console.log(`  ${conflicts.length} conflicting declaration(s) — see the file.`);
if (nearDuplicates.length) console.log(`  ${nearDuplicates.length} possible duplicate(s) — see the file.`);
